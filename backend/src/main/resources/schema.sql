CREATE TABLE IF NOT EXISTS customer_orders (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, customer VARCHAR(100) NOT NULL, product VARCHAR(100) NOT NULL,
 qty INT NOT NULL CHECK(qty>0), price DECIMAL(16,2) NOT NULL CHECK(price>0), due DATE NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'Confirmed', paid DECIMAL(20,2) NOT NULL DEFAULT 0,
 bom BOOLEAN NOT NULL DEFAULT FALSE, po BOOLEAN NOT NULL DEFAULT FALSE, invoiced BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS bom_lines (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, material VARCHAR(100) NOT NULL,
 quantity DECIMAL(16,2) NOT NULL, unit VARCHAR(20) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES customer_orders(id), UNIQUE(order_id, material)
);
CREATE TABLE IF NOT EXISTS purchase_orders (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL UNIQUE, amount DECIMAL(20,2) NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'Draft', FOREIGN KEY(order_id) REFERENCES customer_orders(id)
);
CREATE TABLE IF NOT EXISTS invoices (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL UNIQUE, amount DECIMAL(20,2) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES customer_orders(id)
);
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, amount DECIMAL(20,2) NOT NULL CHECK(amount>0),
 recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(order_id) REFERENCES customer_orders(id)
);
CREATE TABLE IF NOT EXISTS audit_events (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, action VARCHAR(40) NOT NULL,
 recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(order_id) REFERENCES customer_orders(id)
);
